//! `x17 doc`: the SM1 instruction reference, generated from the files the assembler already
//! reads, so it cannot drift from them:
//!
//!   isa.toml        one-syllable forms: name and encoding
//!   subforms.txt    bundle forms: name and per-syllable base words
//!   operands.txt    every form's operand fields
//!   summaries.txt   one plain sentence per form name
//!
//! The reference says what each form does, not how that was established: the notes and the
//! evidence behind them stay in isa.toml and the emulator.
const std = @import("std");
const isa = @import("isa");

const Writer = std.Io.Writer;

pub fn render(out: *Writer) !void {
    try out.writeAll(
        \\# SM1 instruction reference
        \\
        \\Generated by `x17 doc` from `src/isa.toml`, `src/subforms.txt`, `src/operands.txt` and
        \\`src/summaries.txt`. Do not edit: regenerate with `x17 doc > docs/sm1/reference.md`.
        \\The handbook (`handbook.md`) explains the machine; this file lists its forms.
        \\
        \\## One-syllable forms
        \\
        \\
    );
    var it = TomlForms{ .src = isa.isa_toml };
    while (it.next()) |f| try renderForm(out, f);

    try out.writeAll("## Bundle forms\n\n");
    var sf = SubFormRows{ .src = isa.subforms_txt };
    while (sf.next()) |row| try renderSubForm(out, row);
}

const TomlForm = struct {
    name: []const u8 = "",
    mask: []const u8 = "",
    value: []const u8 = "",
};

/// Walks isa.toml's `[[form]]` blocks; every other table is skipped.
const TomlForms = struct {
    src: []const u8,
    pos: usize = 0,

    fn next(self: *TomlForms) ?TomlForm {
        const start = std.mem.indexOfPos(u8, self.src, self.pos, "\n[[form]]\n") orelse return null;
        const body_start = start + "\n[[form]]\n".len;
        const end = std.mem.indexOfPos(u8, self.src, body_start, "\n[") orelse self.src.len;
        self.pos = end;
        var f: TomlForm = .{};
        var lines = std.mem.splitScalar(u8, self.src[body_start..end], '\n');
        while (lines.next()) |line| {
            if (stringValue(line, "name")) |v| f.name = v;
            if (stringValue(line, "mask")) |v| f.mask = v;
            if (stringValue(line, "value")) |v| f.value = v;
        }
        return f;
    }
};

/// `key = "v"` -> v.
fn stringValue(line: []const u8, key: []const u8) ?[]const u8 {
    if (!std.mem.startsWith(u8, line, key)) return null;
    const rest = std.mem.trimStart(u8, line[key.len..], " ");
    if (!std.mem.startsWith(u8, rest, "= \"")) return null;
    const v = rest[3..];
    const q = std.mem.indexOfScalar(u8, v, '"') orelse return null;
    return v[0..q];
}

/// subforms.txt's rows in file order.
const SubFormRows = struct {
    src: []const u8,
    pos: usize = 0,

    fn next(self: *SubFormRows) ?isa.SubForm {
        while (self.pos < self.src.len) {
            const eol = std.mem.indexOfScalarPos(u8, self.src, self.pos, '\n') orelse self.src.len;
            const t = std.mem.trim(u8, self.src[self.pos..eol], " \t\r");
            self.pos = @min(eol + 1, self.src.len);
            if (t.len == 0 or t[0] == '#') continue;
            var tok = std.mem.tokenizeAny(u8, t, " \t");
            const sf = isa.subFormByName(tok.next() orelse continue) orelse continue;
            return sf.*;
        }
        return null;
    }
};

/// The form's sentence from summaries.txt (`name<TAB>sentence`).
fn summary(name: []const u8) ?[]const u8 {
    var lines = std.mem.splitScalar(u8, isa.summaries_txt, '\n');
    while (lines.next()) |line| {
        const tab = std.mem.indexOfScalar(u8, line, '\t') orelse continue;
        if (std.mem.eql(u8, line[0..tab], name)) return std.mem.trim(u8, line[tab + 1 ..], " \r");
    }
    return null;
}

fn renderSummary(out: *Writer, name: []const u8) !void {
    if (summary(name)) |s| try out.print("{s}\n\n", .{s});
}

fn renderForm(out: *Writer, f: TomlForm) !void {
    try out.print("### `{s}`\n\n", .{f.name});
    try renderSummary(out, f.name);
    try out.print("- Encoding: `word & {s} == {s}`\n\n", .{ f.mask, f.value });
    try renderOperands(out, f.name);
}

fn renderSubForm(out: *Writer, sf: isa.SubForm) !void {
    try out.print("### `{s}`\n\n", .{sf.name});
    try renderSummary(out, sf.name);
    try out.print("- Syllables: {d}\n- Base:", .{sf.syllables});
    for (sf.base[0..sf.syllables]) |w| try out.print(" `{x:0>8}`", .{w});
    try out.writeAll("\n\n");
    try renderOperands(out, sf.name);
}

fn renderOperands(out: *Writer, name: []const u8) !void {
    const ops = isa.operandsFor(name);
    if (ops.len == 0) return;
    try out.writeAll("| operand | kind | syllable | bits |\n|---|---|---|---|\n");
    for (ops) |o| {
        if (o.syll == 0) {
            try out.print("| {s} | {s} | head | [{d}:{d}] |\n", .{ o.name, @tagName(o.kind), o.hi, o.lo });
        } else {
            try out.print("| {s} | {s} | s{d} | [{d}:{d}] |\n", .{ o.name, @tagName(o.kind), o.syll, o.hi, o.lo });
        }
    }
    try out.writeAll("\n");
}

const testing = std.testing;

test "the reference covers every form and sub-form, each with a summary" {
    var buf: Writer.Allocating = .init(testing.allocator);
    defer buf.deinit();
    try render(&buf.writer);
    const text = buf.written();
    var key: [80]u8 = undefined;
    for (isa.forms) |f| {
        try testing.expect(std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, "### `{s}`", .{f.name})) != null);
        if (summary(f.name) == null) std.debug.print("form {s} has no summary\n", .{f.name});
        try testing.expect(summary(f.name) != null);
    }
    for (isa.subforms) |sf| {
        try testing.expect(std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, "### `{s}`", .{sf.name})) != null);
        if (summary(sf.name) == null) std.debug.print("sub-form {s} has no summary\n", .{sf.name});
        try testing.expect(summary(sf.name) != null);
    }
}

test "every summary names a form and cites nothing" {
    const banned = [_][]const u8{ "fact ", "pass ", "own-", "OPEN", "wedge", "refuse", "measur", "silicon" };
    var lines = std.mem.splitScalar(u8, isa.summaries_txt, '\n');
    while (lines.next()) |line| {
        if (line.len == 0) continue;
        const tab = std.mem.indexOfScalar(u8, line, '\t') orelse return error.NoTab;
        const name = line[0..tab];
        const known = isa.subFormByName(name) != null or for (isa.forms) |f| {
            if (std.mem.eql(u8, f.name, name)) break true;
        } else false;
        if (!known) std.debug.print("summary for unknown form {s}\n", .{name});
        try testing.expect(known);
        for (banned) |b| if (std.mem.indexOf(u8, line[tab..], b) != null) {
            std.debug.print("summary of {s} carries '{s}'\n", .{ name, b });
            return error.CitationInSummary;
        };
    }
}

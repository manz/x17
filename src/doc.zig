//! `x17 doc`: the SM1 instruction reference, generated from the files the assembler and the
//! emulator already read, so it cannot drift from them:
//!
//!   isa.toml        one-syllable forms: encoding, evidence, ref and their notes
//!   subforms.txt    bundle forms: per-syllable base words and the note block above each row
//!   operands.txt    every form's operand fields
//!   emu.zig         the `///` doc of the handler `named_forms` maps each form to
//!
//! Note lines naming codecs or a vendor are dropped: the reference is interface facts only.
const std = @import("std");
const isa = @import("isa");

const Writer = std.Io.Writer;

const emu_src = @embedFile("emu.zig");

/// Words that mark a note line as being about the image rather than the machine.
const private_words = [_][]const u8{ "App" ++ "le", "AAC", "MP3", "ALAC", "codec" };

pub fn render(out: *Writer) !void {
    try out.writeAll(
        \\# SM1 instruction reference
        \\
        \\Generated by `x17 doc` from `src/isa.toml`, `src/subforms.txt`, `src/operands.txt` and the
        \\emulator's handler notes. Do not edit: regenerate with `x17 doc > docs/sm1/reference.md`.
        \\The handbook (`handbook.md`) explains the machine; this file lists its forms.
        \\
        \\Fact numbers (`fact N`) cite the silicon measurement behind a rule. Bits a form's notes call
        \\OPEN are undefined: the emulator refuses them.
        \\
        \\## One-syllable forms
        \\
        \\
    );
    var it = TomlForms{ .src = isa.isa_toml };
    while (it.next()) |f| try renderForm(out, f);

    try out.writeAll("## Bundle forms\n\n");
    var sf = SubFormNotes{ .src = isa.subforms_txt };
    while (sf.next()) |row| try renderSubForm(out, row);
}

const TomlForm = struct {
    name: []const u8,
    mask: []const u8,
    value: []const u8,
    evidence: []const u8,
    ref: []const u8,
    notes: []const u8,
};

/// Walks isa.toml's `[[form]]` blocks; every other table is skipped.
const TomlForms = struct {
    src: []const u8,
    pos: usize = 0,

    fn next(self: *TomlForms) ?TomlForm {
        const start = std.mem.indexOfPos(u8, self.src, self.pos, "\n[[form]]\n") orelse return null;
        const body_start = start + "\n[[form]]\n".len;
        const end = std.mem.indexOfPos(u8, self.src, body_start, "\n[") orelse self.src.len;
        self.pos = end;
        const body = self.src[body_start..end];
        var f: TomlForm = .{ .name = "", .mask = "", .value = "", .evidence = "", .ref = "", .notes = "" };
        var notes_start: ?usize = null;
        var lines = std.mem.splitScalar(u8, body, '\n');
        var off: usize = 0;
        while (lines.next()) |line| : (off += line.len + 1) {
            if (std.mem.startsWith(u8, line, "#")) {
                if (notes_start == null) notes_start = off;
                continue;
            }
            if (notes_start != null) continue; // keys after the notes (sel = ...) carry no prose
            if (stringValue(line, "name")) |v| f.name = v;
            if (stringValue(line, "mask")) |v| f.mask = v;
            if (stringValue(line, "value")) |v| f.value = v;
            if (stringValue(line, "evidence")) |v| f.evidence = v;
            if (stringValue(line, "ref")) |v| f.ref = v;
        }
        if (notes_start) |n| f.notes = body[n..];
        return f;
    }
};

/// `key = "v"` -> v.
fn stringValue(line: []const u8, key: []const u8) ?[]const u8 {
    if (!std.mem.startsWith(u8, line, key)) return null;
    const rest = std.mem.trimStart(u8, line[key.len..], " ");
    if (!std.mem.startsWith(u8, rest, "= \"")) return null;
    const v = rest[3..];
    const q = std.mem.lastIndexOfScalar(u8, v, '"') orelse return null;
    return v[0..q];
}

const SubFormRow = struct { sf: isa.SubForm, notes: []const u8 };

/// Pairs each subforms.txt row with the comment block directly above it.
const SubFormNotes = struct {
    src: []const u8,
    pos: usize = 0,
    note_start: ?usize = null,

    fn next(self: *SubFormNotes) ?SubFormRow {
        while (self.pos < self.src.len) {
            const eol = std.mem.indexOfScalarPos(u8, self.src, self.pos, '\n') orelse self.src.len;
            const line = self.src[self.pos..eol];
            const here = self.pos;
            self.pos = @min(eol + 1, self.src.len);
            const t = std.mem.trim(u8, line, " \t\r");
            if (t.len == 0) {
                self.note_start = null;
                continue;
            }
            if (t[0] == '#') {
                if (self.note_start == null) self.note_start = here;
                continue;
            }
            const notes = if (self.note_start) |n| self.src[n..here] else "";
            self.note_start = null;
            var tok = std.mem.tokenizeAny(u8, t, " \t");
            const sf = isa.subFormByName(tok.next() orelse continue) orelse continue;
            return .{ .sf = sf.*, .notes = notes };
        }
        return null;
    }
};

fn renderForm(out: *Writer, f: TomlForm) !void {
    try out.print("### `{s}`\n\n", .{f.name});
    try out.print("- Encoding: `word & {s} == {s}`\n", .{ f.mask, f.value });
    if (f.evidence.len != 0) try out.print("- Evidence: {s}\n", .{f.evidence});
    if (f.ref.len != 0 and !isPrivate(f.ref)) try out.print("- Source: {s}\n", .{f.ref});
    try out.writeAll("\n");
    try renderOperands(out, f.name);
    try renderNotes(out, f.notes);
    if (handlerDoc(f.name)) |d| {
        try out.writeAll("Emulator:\n\n");
        try renderNotes(out, d);
    }
}

fn renderSubForm(out: *Writer, row: SubFormRow) !void {
    const sf = row.sf;
    try out.print("### `{s}`\n\n", .{sf.name});
    try out.print("- Syllables: {d}\n- Base:", .{sf.syllables});
    for (sf.base[0..sf.syllables]) |w| try out.print(" `{x:0>8}`", .{w});
    try out.writeAll("\n\n");
    try renderOperands(out, sf.name);
    try renderNotes(out, row.notes);
}

fn renderOperands(out: *Writer, name: []const u8) !void {
    const ops = isa.operandsFor(name);
    if (ops.len == 0) return;
    try out.writeAll("| operand | kind | syllable | bits |\n|---|---|---|---|\n");
    for (ops) |o| {
        const syll: []const u8 = if (o.syll == 0) "head" else "";
        if (syll.len != 0) {
            try out.print("| {s} | {s} | head | [{d}:{d}] |\n", .{ o.name, @tagName(o.kind), o.hi, o.lo });
        } else {
            try out.print("| {s} | {s} | s{d} | [{d}:{d}] |\n", .{ o.name, @tagName(o.kind), o.syll, o.hi, o.lo });
        }
    }
    try out.writeAll("\n");
}

/// Comment lines (`#` or `///`) as a quoted block, private lines dropped.
fn renderNotes(out: *Writer, notes: []const u8) !void {
    var wrote = false;
    var lines = std.mem.splitScalar(u8, notes, '\n');
    while (lines.next()) |raw| {
        const t = std.mem.trim(u8, raw, " \t\r");
        const text = if (std.mem.startsWith(u8, t, "///"))
            t[3..]
        else if (std.mem.startsWith(u8, t, "#"))
            t[1..]
        else
            continue;
        if (isPrivate(text)) continue;
        try out.print(">{s}\n", .{text});
        wrote = true;
    }
    if (wrote) try out.writeAll("\n");
}

fn isPrivate(text: []const u8) bool {
    for (private_words) |w| if (std.mem.indexOf(u8, text, w) != null) return true;
    return false;
}

/// The `///` block above the handler `named_forms` maps `form` to, read from emu.zig's source.
fn handlerDoc(form: []const u8) ?[]const u8 {
    var key_buf: [64]u8 = undefined;
    const key = std.fmt.bufPrint(&key_buf, ".{{ \"{s}\", ", .{form}) catch return null;
    const at = std.mem.indexOf(u8, emu_src, key) orelse return null;
    const eol = std.mem.indexOfScalarPos(u8, emu_src, at, '\n') orelse return null;
    const entry = emu_src[at..eol];
    const ex = std.mem.indexOf(u8, entry, "exec") orelse return null;
    var e = ex;
    while (e < entry.len and (std.ascii.isAlphanumeric(entry[e]) or entry[e] == '_')) e += 1;
    var fn_buf: [80]u8 = undefined;
    const decl = std.fmt.bufPrint(&fn_buf, "\nfn {s}(", .{entry[ex..e]}) catch return null;
    const fn_at = std.mem.indexOf(u8, emu_src, decl) orelse return null;
    // Walk back over the contiguous `///` lines.
    var start = fn_at;
    while (start > 0) {
        const prev_eol = start;
        const prev_start = if (std.mem.lastIndexOfScalar(u8, emu_src[0..prev_eol], '\n')) |p| p else 0;
        const line = std.mem.trim(u8, emu_src[prev_start..prev_eol], " \n");
        if (!std.mem.startsWith(u8, line, "///")) break;
        start = prev_start;
    }
    if (start == fn_at) return null;
    return emu_src[start..fn_at];
}

const testing = std.testing;

test "the reference covers every form and sub-form" {
    var buf: Writer.Allocating = .init(testing.allocator);
    defer buf.deinit();
    try render(&buf.writer);
    const text = buf.written();
    for (isa.forms) |f| {
        var key: [80]u8 = undefined;
        try testing.expect(std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, "### `{s}`", .{f.name})) != null);
    }
    for (isa.subforms) |sf| {
        var key: [80]u8 = undefined;
        try testing.expect(std.mem.indexOf(u8, text, try std.fmt.bufPrint(&key, "### `{s}`\n\n- Syllables: {d}", .{ sf.name, sf.syllables })) != null);
    }
}

test "the reference carries no table section and no private note" {
    var buf: Writer.Allocating = .init(testing.allocator);
    defer buf.deinit();
    try render(&buf.writer);
    const text = buf.written();
    try testing.expect(std.mem.indexOf(u8, text, "[tables.") == null);
    for (private_words) |w| try testing.expect(std.mem.indexOf(u8, text, w) == null);
}

test "a named form gets its handler's doc" {
    try testing.expect(handlerDoc("dld") != null);
    try testing.expect(handlerDoc("no-such-form") == null);
}
